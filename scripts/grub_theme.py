#!/usr/bin/env python3
"""Build the LW GRUB theme from the current wallpaper and palette.

  python3 scripts/grub_theme.py [OUT_DIR]

Writes theme.txt, background.png, the select_*.png pixmaps and the fonts (.pf2) to
OUT_DIR (default ~/.local/state/rice-minimal/grub/lw) and prints the sudo commands
that install it. Nothing outside OUT_DIR is touched: /boot and /etc/default/grub
need root, so they are left to those commands.

The look follows the LW windows: the wallpaper blurred under a dark veil, a mono
font, the accent for the title and the chosen entry (with a bar on its left), dim
text for the rest and the two corner marks.
"""
import json
import os
import shutil
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
HOME = Path(os.environ.get('HOME', str(Path.home())))
OUT = Path(sys.argv[1]) if len(sys.argv) > 1 else HOME/'.local/state/rice-minimal/grub/lw'
PALETTE = HOME/'.config/noctalia/palettes/RiceMinimal.json'
FONTS = Path('/usr/share/fonts/TTF')
REGULAR = FONTS/'JetBrainsMonoNerdFontMono-Regular.ttf'
BOLD = FONTS/'JetBrainsMonoNerdFontMono-Bold.ttf'
W, H = 1920, 1080
# Latin with accents, arrows, box drawing and ⏎: enough for menu titles and hints.
RANGES = '0x20-0x7E,0xA0-0x24F,0x2190-0x21FF,0x2500-0x257F,0x23CE-0x23CE'


def run(*cmd):
    subprocess.run(cmd, check=True, capture_output=True, text=True)


def mix(a, b, t):
    pa = [int(a[i:i+2], 16) for i in (1, 3, 5)]
    pb = [int(b[i:i+2], 16) for i in (1, 3, 5)]
    return '#' + ''.join(f'{round(x + (y - x) * t):02x}' for x, y in zip(pa, pb))


def colors():
    status = subprocess.run([sys.executable, str(ROOT/'extras'/'rice.py'), 'status', '--json'],
                            capture_output=True, text=True, timeout=30)
    data = json.loads(status.stdout)['data']
    dark = json.loads(PALETTE.read_text())['dark']
    bg, fg, variant = dark['mSurface'], dark['mOnSurface'], dark['mOnSurfaceVariant']
    return {
        'wallpaper': (data.get('wallpaper') or {}).get('effective') or '',
        'bg': bg, 'fg': fg,
        'dim': mix(bg, variant, 0.85), 'faint': mix(bg, variant, 0.55),
        'accent': (data.get('terminal') or {}).get('accent') or dark['mPrimary'],
    }


def background(c, path):
    # The wallpaper filling the screen, blurred, under the bg at 72% (the LW veil),
    # darker on the left where the menu sits.
    veil = ['(', '-size', f'{W}x{H}', f'xc:{c["bg"]}', '-alpha', 'set', '-channel', 'A', '-evaluate', 'set', '72%', '+channel', ')']
    side = ['(', '-size', f'{H}x{W}', f'gradient:{c["bg"]}C0-{c["bg"]}00', '-rotate', '-90', ')']
    if c['wallpaper'] and Path(c['wallpaper']).is_file():
        base = [c['wallpaper'], '-resize', f'{W}x{H}^', '-gravity', 'center', '-extent', f'{W}x{H}', '-blur', '0x14']
    else:
        base = ['-size', f'{W}x{H}', f'xc:{c["bg"]}']
    run('magick', *base, *veil, '-composite', *side, '-composite', '-alpha', 'off', str(path))


def pixmaps(c, out):
    # Chosen entry: a 4 px accent bar on the left and a faint accent fill.
    run('magick', '-size', '4x1', f'xc:{c["accent"]}', str(out/'select_w.png'))
    run('magick', '-size', '1x1', f'xc:{c["accent"]}1f', str(out/'select_c.png'))


def fonts(out):
    # pf2 names come out as "<name> <style> <size>": "LW Mono Regular 20" and so on.
    made = {}
    for ttf, style in ((REGULAR, 'Regular'), (BOLD, 'Bold')):
        for size in (16, 20, 34):
            name = f'lw-{style.lower()}-{size}.pf2'
            run('grub-mkfont', '-n', 'LW Mono', '-s', str(size), '-r', RANGES, '-o', str(out/name), str(ttf))
            made[(style, size)] = f'LW Mono {style} {size}'
    return made


def theme(c, f):
    return f'''# LW — GRUB theme, generated by scripts/grub_theme.py. Do not edit by hand.
title-text: ""
desktop-image: "background.png"
desktop-color: "{c["bg"]}"
terminal-font: "{f[("Regular", 16)]}"
terminal-box: ""
terminal-left: "8%"
terminal-top: "10%"
terminal-width: "84%"
terminal-height: "80%"
terminal-border: "0"

+ label {{ left = 3% top = 4% text = "┌" font = "{f[("Regular", 20)]}" color = "{c["dim"]}" }}
+ label {{ left = 96% top = 4% text = "┐" font = "{f[("Regular", 20)]}" color = "{c["dim"]}" }}
+ label {{ left = 3% top = 93% text = "└" font = "{f[("Regular", 20)]}" color = "{c["dim"]}" }}
+ label {{ left = 96% top = 93% text = "┘" font = "{f[("Regular", 20)]}" color = "{c["dim"]}" }}

+ label {{
  left = 10%
  top = 20%
  text = "LW // BOOT"
  font = "{f[("Bold", 34)]}"
  color = "{c["accent"]}"
}}
+ label {{
  left = 10%
  top = 26%
  text = "// escolha o sistema"
  font = "{f[("Regular", 16)]}"
  color = "{c["dim"]}"
}}

+ boot_menu {{
  left = 10%
  top = 33%
  width = 48%
  height = 48%
  item_font = "{f[("Regular", 20)]}"
  selected_item_font = "{f[("Bold", 20)]}"
  item_color = "{c["dim"]}"
  selected_item_color = "{c["accent"]}"
  icon_width = 0
  icon_height = 0
  item_icon_space = 0
  item_height = 44
  item_padding = 18
  item_spacing = 6
  selected_item_pixmap_style = "select_*.png"
  scrollbar = false
}}

+ label {{
  id = "__timeout__"
  left = 10%
  top = 84%
  text = "inicia em %d s"
  font = "{f[("Regular", 16)]}"
  color = "{c["accent"]}"
}}
+ label {{
  left = 10%
  top = 88%
  text = "↑↓ escolher   ⏎ iniciar   e editar   c console"
  font = "{f[("Regular", 16)]}"
  color = "{c["dim"]}"
}}
'''


def main():
    for tool in ('magick', 'grub-mkfont'):
        if not shutil.which(tool):
            sys.exit(f'falta {tool}')
    OUT.mkdir(parents=True, exist_ok=True)
    c = colors()
    background(c, OUT/'background.png')
    pixmaps(c, OUT)
    f = fonts(OUT)
    (OUT/'theme.txt').write_text(theme(c, f))
    print(f'tema LW em {OUT}')
    print('instalar (sudo):')
    print(f'  sudo install -Dm644 -t /boot/grub/themes/lw {OUT}/*')
    print('  sudo grub-mkconfig -o /boot/grub/grub.cfg')


if __name__ == '__main__':
    main()
